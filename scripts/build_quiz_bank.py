CHANNEL_LABEL = {"paleo": "パレオな男", "tussi": "料理科学(つっしー)", "ai": "AI関連"}


def main():
    total_questions = sum(len(q) for _, _, _, _, q in ARTICLES)
    if total_questions != len(EXPLANATIONS):
        raise ValueError(
            f"EXPLANATIONS has {len(EXPLANATIONS)} entries but there are "
            f"{total_questions} questions; keep them in the same order and count."
        )

    wb = openpyxl.Workbook()
    ws = wb.active
    ws.title = "quiz_bank"
    ws.append([
        "day_index", "channel", "channel_label", "article_title", "article_url",
        "published_date", "q_no", "question", "choice_a", "choice_b", "choice_c",
        "choice_d", "correct", "explanation",
    ])
    explanation_iter = iter(EXPLANATIONS)
    for day_index, (channel, title, url, published, questions) in enumerate(ARTICLES, start=1):
        for q_no, (question, choices, correct_idx) in enumerate(questions, start=1):
            ws.append([
                day_index, channel, CHANNEL_LABEL[channel], title, url, published,
                q_no, question, choices[0], choices[1], choices[2], choices[3],
                "ABCD"[correct_idx], next(explanation_iter),
            ])
    for col, width in zip("ABCDEFGHIJKLMN", [10, 8, 18, 45, 40, 12, 6, 45, 22, 22, 22, 22, 9, 55]):
        ws.column_dimensions[col].width = width
    out_path = "data/quiz/quiz_bank.xlsx"
    wb.save(out_path)
    print(f"wrote {out_path}: {len(ARTICLES)} articles x 4 questions = {len(ARTICLES) * 4} questions")


if __name__ == "__main__":
    main()
