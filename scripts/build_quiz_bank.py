def main():
    total_questions = sum(len(q) for _, _, _, _, q in ARTICLES)
    if total_questions != len(EXPLANATIONS):
        raise ValueError(
            f"EXPLANATIONS has {len(EXPLANATIONS)} entries but there are "
            f"{total_questions} questions; keep them in the same order and count."
        )
    if len(PSYCHOLOGY_BONUS) != len(ARTICLES):
        raise ValueError(
            f"PSYCHOLOGY_BONUS has {len(PSYCHOLOGY_BONUS)} entries but there are "
            f"{len(ARTICLES)} days; keep a 1:1 mapping so every day gets one bonus question."
        )

    wb = openpyxl.Workbook()
    ws = wb.active
    ws.title = "quiz_bank"
    ws.append([
        "day_index", "channel", "channel_label", "article_title", "article_url",
        "published_date", "q_no", "question", "choice_a", "choice_b", "choice_c",
        "choice_d", "correct", "explanation",
    ])
    explanation_iter = iter(EXPLANATIONS)
    for day_index, (channel, title, url, published, questions) in enumerate(ARTICLES, start=1):
        for q_no, (question, choices, correct_idx) in enumerate(questions, start=1):
            ws.append([
                day_index, channel, CHANNEL_LABEL[channel], title, url, published,
                q_no, question, choices[0], choices[1], choices[2], choices[3],
                "ABCD"[correct_idx], next(explanation_iter),
            ])
    for col, width in zip("ABCDEFGHIJKLMN", [10, 8, 18, 45, 40, 12, 6, 45, 22, 22, 22, 22, 9, 55]):
        ws.column_dimensions[col].width = width

    ws2 = wb.create_sheet("psychology_bonus")
    ws2.append([
        "day_index", "article_title", "article_url", "published_date", "question",
        "choice_a", "choice_b", "choice_c", "choice_d", "correct", "explanation",
    ])
    for day_index, (title, url, published, question, choices, correct_idx, explanation) in enumerate(
        PSYCHOLOGY_BONUS, start=1
    ):
        ws2.append([
            day_index, title, url, published, question,
            choices[0], choices[1], choices[2], choices[3],
            "ABCD"[correct_idx], explanation,
        ])
    for col, width in zip("ABCDEFGHIJK", [10, 45, 40, 12, 45, 22, 22, 22, 22, 9, 55]):
        ws2.column_dimensions[col].width = width

    out_path = "data/quiz/quiz_bank.xlsx"
    wb.save(out_path)
    print(
        f"wrote {out_path}: {len(ARTICLES)} articles x 4 questions = "
        f"{len(ARTICLES) * 4} questions + {len(PSYCHOLOGY_BONUS)} psychology bonus questions"
    )


if __name__ == "__main__":
    main()
